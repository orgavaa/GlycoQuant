# ---------------------------------------------------------------------------
# Backward-compatible Palette dataclass (used by radial_profile.py etc.)
# ---------------------------------------------------------------------------

from dataclasses import dataclass


@dataclass(frozen=True)
class Palette:
    bg_base: str = "#FFFFFF"
    bg_subtle: str = "#F8FAFC"
    bg_muted: str = "#F1F5F9"
    bg_elevated: str = "#FFFFFF"
    border_subtle: str = "#E2E8F0"
    border_strong: str = "#CBD5E1"
    text_primary: str = TEXT_PRIMARY
    text_secondary: str = TEXT_SECONDARY
    text_muted: str = TEXT_MUTED
    accent_primary: str = ACCENT_BLUE
    accent_brand: str = "#0D9488"
    accent_violet: str = "#7C3AED"
    accent_amber: str = "#F59E0B"
    success: str = "#16A34A"
    warning: str = "#EA580C"
    error: str = "#DC2626"
    info: str = ACCENT_BLUE


PALETTE = Palette()


def get_plotly_layout_template() -> dict:
    """Publication-grade Plotly layout template.

    Apply via ``fig.update_layout(**get_plotly_layout_template())``
    in every ``glycoquant.viz`` factory.
    """
    return {
        "paper_bgcolor": "rgba(0,0,0,0)",
        "plot_bgcolor": "rgba(0,0,0,0)",
        "font": {
            "family": FONT_FAMILY,
            "color": TEXT_SECONDARY,
            "size": 11,
        },
        "title": {
            "font": {
                "family": FONT_FAMILY,
                "size": 13,
                "color": TEXT_PRIMARY,
            },
            "x": 0.0,
            "xanchor": "left",
        },
        "xaxis": {
            "gridcolor": GRID_COLOR,
            "zerolinecolor": ZEROLINE_COLOR,
            "linecolor": ZEROLINE_COLOR,
            "tickfont": {"color": TEXT_MUTED, "size": 10, "family": FONT_FAMILY},
            "title": {"font": {"color": TEXT_SECONDARY, "size": 11}},
        },
        "yaxis": {
            "gridcolor": GRID_COLOR,
            "zerolinecolor": ZEROLINE_COLOR,
            "linecolor": ZEROLINE_COLOR,
            "tickfont": {"color": TEXT_MUTED, "size": 10, "family": FONT_FAMILY},
            "title": {"font": {"color": TEXT_SECONDARY, "size": 11}},
        },
        "legend": {
            "bgcolor": "rgba(255,255,255,0.9)",
            "font": {"color": TEXT_SECONDARY, "size": 10},
        },
        "colorway": COLORBREWER_SET2,
        "margin": {"l": 50, "r": 20, "t": 30, "b": 50},
    }
