"""GlycoQuant visual design tokens — publication-grade scientific figures.

A single source of truth for palettes, typography, and Plotly layout.
All charts generated by ``glycoquant.viz.*`` use these settings so
figures are consistent whether shown in the React frontend, a Jupyter
notebook, or exported for a manuscript.

Design principles:
- ColorBrewer Set2 for categorical data (Nature Methods standard)
- RdBu diverging (centered on zero) for correlation matrices
- Viridis sequential for feature intensities
- Inter font for all text
- Transparent backgrounds (cards provide the white)
- Minimal gridlines, no modebar
"""
from __future__ import annotations

# ---------------------------------------------------------------------------
# ColorBrewer palettes (perceptually uniform, colorblind-safe)
# ---------------------------------------------------------------------------

# Set2 — qualitative, up to 8 categories (Nature Methods, Cell Systems standard)
COLORBREWER_SET2 = [
    "#66c2a5", "#fc8d62", "#8da0cb", "#e78ac3",
    "#a6d854", "#ffd92f", "#e5c494", "#b3b3b3",
]

# Dark2 — qualitative, higher contrast variant
COLORBREWER_DARK2 = [
    "#1b9e77", "#d95f02", "#7570b3", "#e7298a",
    "#66a61e", "#e6ab02", "#a6761d", "#666666",
]

